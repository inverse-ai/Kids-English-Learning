import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {hydrateProfiles,exportProfile,validateExport,restoreProfile,syncProfile,selectProfile} from '../dist/progress-store.js';
import {validResume} from '../dist/home-page.js';
const backup=validateExport(await readFile(new URL('./fixtures/pre-organisation-profile.json',import.meta.url),'utf8'));
const p=hydrateProfiles(null);restoreProfile(p,backup);
assert.deepEqual(p.learning,backup.data.learning);
assert.deepEqual(p.pictureFamilies,backup.data.pictureFamilies);
assert.equal(p.learning.playful.lessons['letter:a'].step,4);
assert.deepEqual(p.learning.playful.lessons['letter:a'].completed,[0,1,2]);
assert.deepEqual(p.learning.playful.lessons['letter:a'].work[4].trace,[[[.2,.3],[.4,.6]]]);
const original=structuredClone(p.profileData.big);
p.learning.sentenceWriting={current:'hen-sun-0',lessons:{'hen-sun-0':{word:1,words:{0:{drawing:[[[.2,.3],[.6,.7]]],showGuide:false,done:true}},done:false}}};
p.learning.playful.lessons['letter:a'].work[4].traceDrafts={upper:[[[.2,.3],[.4,.6]]],lower:[[[.3,.3],[.5,.8]]]};
const file=validateExport(JSON.stringify(exportProfile(p,'little')));
assert.equal(file.data.learning.sentenceWriting.lessons['hen-sun-0'].word,1);
assert.deepEqual(file.data.learning.playful.lessons['letter:a'].work[4].traceDrafts,p.learning.playful.lessons['letter:a'].work[4].traceDrafts);
syncProfile(p,'little');selectProfile(p,'big');assert.deepEqual(p.profileData.big,original);assert.equal(p.learning.sentenceWriting,undefined);
selectProfile(p,'little');assert.equal(p.learning.sentenceWriting.lessons['hen-sun-0'].word,1);
const next=hydrateProfiles(null);restoreProfile(next,file);assert.deepEqual(next.learning.sentenceWriting,p.learning.sentenceWriting);
next.learning.sentenceWriting.lessons['hen-sun-0'].word=2;restoreProfile(next,file);assert.equal(next.learning.sentenceWriting.lessons['hen-sun-0'].word,2);
const invalid=structuredClone(file);invalid.data.learning.sentenceWriting.lessons['hen-sun-0'].words[0].drawing=[[[2,2]]];assert.throws(()=>validateExport(JSON.stringify(invalid)));
assert.deepEqual(validResume({kind:'stage',page:'sentence-writing',id:'hen-sun-0'}),{kind:'stage',page:'sentence-writing',id:'hen-sun-0'});
assert.equal(validResume({kind:'stage',page:'sentence-writing',id:'unknown'}),null);
console.log('PASS: prior exports, existing lesson positions/drawings, separate profiles, tracing drafts, new sentence writing, additive restore and invalid-file validation.');
